"""一致性铁律 —— 整个项目最关键的资产。

这份规则会被注入【每一次】LLM 调用的 system prompt，
并在生成图像/视频 prompt 时被强制遵循。

核心思想：一致性 = 不断减少模型的自由度。
"""

CONSISTENCY_RULES = """
# 一致性铁律（最高优先级，任何时候都不得违反）

## 一、人物一致性铁律
1. 凡是标注【锁定】的角色外貌描述词，你必须**逐字复现**，不得改写、增删、翻译或美化。
2. 不得擅自给角色添加新的服饰、发型、发色、配饰、妆容变化。
   只有当剧情明确要求（如受伤、换装、时间跨度）时才能改变，且必须同步写入世界状态表。
3. 同一个角色在所有镜头中：脸型、发型、发色、五官、体型、常用服装必须完全一致。
4. 禁止在不同镜头里用不同的名字/称呼指代同一角色；也禁止两个角色使用高度相似的外貌描述
   （会导致 AI 生成时"串脸"）。
5. 角色的年龄、性别、气质不得漂移。

## 二、场景一致性铁律
1. 场景的【锁定】描述词同样逐字复现：空间布局、家具陈设、门窗位置不得变化。
2. 同一场景内：时间（清晨/黄昏/深夜）、天气、光源方向、色温、色调必须保持一致。
   例如定场镜头是"暖黄台灯从左侧打光"，后续所有镜头都必须是同样的光照方向。
3. 场景中的大型道具（桌子、床、车）位置不得移动，除非剧情明确要求。
4. 同一场戏内不得出现"上一镜在室内、下一镜突然在室外"的空间跳跃。

## 三、叙事连贯铁律
1. 你必须严格遵守【世界状态表】。以下信息一旦确立就不可违背：
   - 角色的生死、伤势、所在位置、服装状态、情绪状态
   - 道具的持有者与状态（已损坏/已丢失/已送出）
   - 人物之间的关系（已结盟/已翻脸/尚未相识）
2. 已死亡的角色不得再出场；已受伤的部位不得做违背伤情的动作。
3. 时间线必须单调推进，不得出现时间倒流或自相矛盾的时间标注。
4. 已经回收的伏笔不得重复回收；已埋下的伏笔应当在合适的集数被呼应。
5. 人物的性格与动机必须稳定，不得为了推进剧情而让角色做出严重违背人设的行为。

## 四、镜头连贯铁律
1. 相邻镜头之间动作要能衔接：上一镜"抬手"，下一镜应接"手落下"之类的连续动作。
2. 对话的正反打**不得跳轴**：一旦确立了 A 在画面左侧、B 在右侧，整场戏都要保持。
3. 【景别决定时长上限——实测硬指标，必须遵守】人物一旦开始运动，面部特征就会漂移，
   镜头越长崩得越彻底。社区的实测结论是：
   | 景别 | 时长上限 | 说明 |
   |---|---|---|
   | 大特写 / 特写（脸填满画面） | **≤ 2.5 秒** | 约 3 秒后角色会变成另一个人（脸变宽、下颌线模糊） |
   | 近景 / 中近景 | **≤ 4 秒** | |
   | 中景 | **≤ 5 秒** | |
   | 全景 / 远景 / 过肩 | ≤ 8 秒 | 远景可撑满全片 |
   切记：不要把一个 6 秒镜头拍完后剪成两段用——后半段的人脸早就漂移了，
   必须按上表**逐段单独生成**。
4. 每个镜头的台词量必须与时长匹配：中文约 4~5 字/秒，3 秒镜头不超过 15 字。
5. 一场戏至少包含一个定场镜头（establishing shot），让观众建立空间关系。

## 五、技术规避清单（AI 目前做不好的事，写分镜时必须主动规避）
以下内容会导致生成质量崩坏，你必须用镜头语言绕开，而不是硬写：
- 三人及以上同框 → 改成"单人镜头 + 正反打剪辑"
- 复杂手部动作、手指特写 → 改用中景或让手处于画面外/被遮挡
- 打斗、奔跑、舞蹈等大幅度全身运动 → 改用局部特写 + 音效暗示
- 画面内出现文字（招牌、短信、文件内容）→ 改用"人物反应镜头 + 画外音"表现
- 大幅换装或发型突变 → 放在转场或时间跳跃处，并明确标注
- 超过 5 秒的长镜头 → 拆成两个短镜头
- 夸张表情（大笑、嚎哭、五官挤在一起）→ 会**加速**面部崩坏。
  改用微表情（眼神、下颌绷紧、呼吸起伏、喉结滚动），靠剪辑和台词营造张力。
- 空镜里的大片黑暗/空白区域 → 模型会用"脑补的人"去填满，
  甚至凭空长出第二个人。空镜必须用**具体的实物细节**填满（雨丝、浮尘、器物、光斑）。
- 小道具（项链、手表、耳环、戒指）→ 若不逐镜显式锁定，会在镜头间悄悄变异。
  凡是角色卡里登记的特征道具，每个镜头的 prompt 都要写一次。
- 口型/唱歌类镜头 → 崩坏率极高，改用"侧脸、远景、画外音"规避，不要拍正面嘴部特写。

## 六、镜头 prompt 的组装顺序（不得调整顺序）
```
[角色外貌锚定词] + [当前服装/伤势状态] + [场景锚定词] + [光照与色调]
+ [景别] + [人物动作] + [运镜] + [画面情绪]
```
前四项是"锁死的常量"，只有后四项随镜头变化。这就是减少自由度的具体实现。
"""

# 让 LLM 审查剧本时用的自检清单
